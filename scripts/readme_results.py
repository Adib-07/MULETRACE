"""README numbers come only from eval/ files.

  python scripts/readme_results.py          regenerate the generated blocks in README.md
  python scripts/readme_results.py --check  exit 1 if README.md or web/index.html disagree with eval/ files
"""
import json, re, sys

def load(name):
    return json.load(open("eval/" + name))

std = {m["model"][0]: {**m, **load("report.json")["models"][m["model"]]} for m in load("metrics.json")}
shf = {m["model"][0]: {**m, **load("report_shuf.json")["models"][m["model"]]} for m in load("metrics_shuf.json")}
rep, lat, env = load("report.json"), load("latency.json"), load("environment.json")
dd, eg = load("detection_delay.json"), load("egress.json")
pct = lambda v: f"{v * 100:.1f}%"
ci = lambda m: f"{m['pr_auc']:.4f} ({m['pr_auc_ci95'][0]:.3f}–{m['pr_auc_ci95'][1]:.3f})"
names = {"A": "A · Transaction-only XGBoost", "B": "B · Simple rules", "N": "N · Network features only", "C": "**C · MuleTrace (all 20 features)**"}

def table(ms):
    rows = ["| Model | PR-AUC (95% CI) | Recall | Precision | Review | FP / 1,000 | P@100 |", "|---|---|---:|---:|---:|---:|---:|"]
    for k in "ABNC":
        m = ms[k]
        rows.append(f"| {names[k]} | {ci(m)} | {pct(m['recall'])} | {pct(m['precision'])} | {m['review_pct']:.2f}% | {m['fp_per_1000']:.2f} | {m['precision_at_k']['100']:.2f} |")
    return "\n".join(rows)

sC, sA, uC = shf["C"], shf["A"], std["C"]
ip, fl, hp = lat["inproc"]["all"], lat["inproc"]["flag_or_hold_only"], lat["http_50rps"]
eg_line = f"{len(eg['non_loopback_connections'])} non-loopback connections of the API process in {eg['samples']} socket samples while scoring {eg['payments_scored_during_check']:,} payments ([`eval/egress.json`](eval/egress.json))"
dd_line = (f"**{dd['detected_pct']}%** of the {dd['attempts_in_test_window']} IBM-labelled laundering attempts that start in the test window get a FLAG/HOLD; "
           f"median delay **{dd['delay_minutes']['median']:g} min** from the attempt's first payment (p90 {dd['delay_minutes']['p90']:.0f} min) "
           f"([`eval/detection_delay.json`](eval/detection_delay.json), {dd['status'].split(':')[0]}, pattern match {dd['match_rate'] * 100:.0f}%)")

RESULTS = f"""<!-- results:start (generated by scripts/readme_results.py from eval/) -->
## TL;DR

- **Conservative headline (order-shuffled run): PR-AUC {sC['pr_auc']:.3f} vs {sA['pr_auc']:.3f}** for a transaction-only model ({sC['pr_auc'] / sA['pr_auc']:.0f}×), recall {pct(sC['recall'])} vs {pct(sA['recall'])}, about 1 in {round(1 / sC['precision'])} flags is laundering. Standard run (upper bound): PR-AUC {uC['pr_auc']:.3f}, recall {pct(uC['recall'])}.
- **Why two numbers:** timestamps are per minute, so the order inside a minute is only file order. The shuffled run randomises that order before building features, so the model cannot benefit from it.
- **Time to detect:** {dd_line}.
- **About {ip['p50']:.1f} ms per decision on IBM z17** (in-process p50 {ip['p50']:.2f} ms, p99 {ip['p99']:.2f} ms over {ip['n']:,} payments; HTTP at {hp['target_rate']:.0f} req/s for {hp['seconds']:.0f} s: {hp['sent']:,} requests, {sum(hp['errors'].values())} errors, server-side p99 {hp['server_latency_ms']['p99']:.2f} ms). Data egress measured: {eg_line}.

## Results

IBM AML HI-Small (synthetic), first 2,000,000 payments by time, split 60/20/20 by time. Test: {rep['rows']['test']:,} payments, {rep['positives']['test']} laundering. Thresholds from validation only.

**Conservative: order shuffled within each minute** ([`eval/report_shuf.md`](eval/report_shuf.md))

{table(shf)}

**Standard run, upper bound** ([`eval/report.md`](eval/report.md))

{table(std)}

- Network signals carry the lift: in both runs, network-only beats transaction-only on PR-AUC ({shf['N']['pr_auc']:.3f} vs {sA['pr_auc']:.3f} conservative) and the combination beats both. In the conservative run, network-only recall ({pct(shf['N']['recall'])}) is below transaction-only ({pct(sA['recall'])}).
- About 1 in {round(1 / sC['precision'])} FLAGs is laundering (conservative run); the rest are false alarms, so a person decides. {pct(1 - sC['recall'])} of laundering payments are still missed at this review budget (conservative run).
<!-- results:end -->"""

IBMZ = f"""<!-- ibmz:start (generated by scripts/readme_results.py from eval/) -->
Source: [`eval/latency.json`](eval/latency.json), [`eval/environment.json`](eval/environment.json), [`eval/egress.json`](eval/egress.json). Measured on the VM: {env['uname_m']}, machine type {env['machine_type']}, {env['cpus']} vCPU, {env['mem_gib']} GiB RAM, {env['os']}, Python {env['python']}.

| Measurement | p50 | p95 | p99 |
|---|---:|---:|---:|
| In-process decision, {ip['n']:,} test payments | {ip['p50']:.2f} ms | {ip['p95']:.2f} ms | {ip['p99']:.2f} ms |
| … FLAG/HOLD only (adds explanations and the alert write), {fl['n']:,} payments | {fl['p50']:.2f} ms | {fl['p95']:.2f} ms | {fl['p99']:.2f} ms |
| HTTP `/score`, {hp['target_rate']:.0f} req/s for {hp['seconds']:.0f} s ({hp['sent']:,} requests, {sum(hp['errors'].values())} errors): server-side | {hp['server_latency_ms']['p50']:.2f} ms | {hp['server_latency_ms']['p95']:.2f} ms | {hp['server_latency_ms']['p99']:.2f} ms |
| … client round trip on the same machine | {hp['client_round_trip_ms']['p50']:.2f} ms | {hp['client_round_trip_ms']['p95']:.2f} ms | {hp['client_round_trip_ms']['p99']:.2f} ms |

- **Data stays put, measured:** {eg_line}.
<!-- ibmz:end -->"""

JUDGING = [f"{env['uname_m']}, machine type {env['machine_type']}, {env['cpus']} vCPU, {env['mem_gib']} GiB",
           f"p50 {ip['p50']:.2f} ms and p99 {ip['p99']:.2f} ms over {ip['n']:,} payments",
           f"{hp['sent']:,} requests, {sum(hp['errors'].values())} errors"]
METRIC_VALUES = [f"{m['pr_auc']:.4f}" for m in list(std.values()) + list(shf.values())] + [f"{ip['p50']:.2f} ms", f"{dd['detected_pct']}%"]

def apply(readme):
    for name, block in (("results", RESULTS), ("ibmz", IBMZ)):
        pat = rf"<!-- {name}:start.*?<!-- {name}:end -->"
        if re.search(pat, readme, re.S):
            readme = re.sub(pat, lambda _: block, readme, flags=re.S)
        elif name == "ibmz":                                  # first run: replace the hand-written table
            a = readme.index("## Why IBM Z\n") + len("## Why IBM Z\n")
            b = readme.index("- **Data stays put.**")
            end = readme.index("\n", b)
            readme = readme[:a] + "\n" + block + "\n" + readme[end + 1:]
        else:
            raise SystemExit("README has no results block")
    return readme

readme = open("README.md").read()
if "--check" in sys.argv:
    problems = []
    if apply(readme) != readme:
        problems.append("README generated blocks are out of date: run python scripts/readme_results.py")
    problems += [f"README judging section lacks '{s}'" for s in JUDGING if s not in readme]
    html = open("web/index.html").read()
    code = "\n".join(l for l in html.splitlines() if "SAMPLE_" not in l)    # demo sample lines are recorded data
    problems += [f"web/index.html hard-codes eval value {v}" for v in METRIC_VALUES if v in code]
    print("\n".join(problems) or f"OK: README blocks match eval/, judging numbers present, UI has no hard-coded eval metrics ({len(METRIC_VALUES)} values checked)")
    sys.exit(1 if problems else 0)
open("README.md", "w").write(apply(readme))
print("README generated blocks regenerated")
