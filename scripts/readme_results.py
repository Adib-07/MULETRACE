"""Regenerates the README results block from eval/ files (no hand-copied numbers). Run: python scripts/readme_results.py"""
import json, re

def load(name):
    return json.load(open("eval/" + name))

std = {m["model"][0]: {**m, **load("report.json")["models"][m["model"]]} for m in load("metrics.json")}
shf = {m["model"][0]: {**m, **load("report_shuf.json")["models"][m["model"]]} for m in load("metrics_shuf.json")}
rep, lat = load("report.json"), load("latency.json")
pct = lambda v: f"{v * 100:.1f}%"
ci = lambda m: f"{m['pr_auc']:.4f} ({m['pr_auc_ci95'][0]:.3f}–{m['pr_auc_ci95'][1]:.3f})"
names = {"A": "A · Transaction-only XGBoost", "B": "B · Simple rules", "N": "N · Network features only", "C": "**C · MuleTrace (all 20 features)**"}

def table(ms):
    rows = ["| Model | PR-AUC (95% CI) | Recall | Precision | Review | FP / 1,000 | P@100 |", "|---|---|---:|---:|---:|---:|---:|"]
    for k in "ABNC":
        m = ms[k]
        rows.append(f"| {names[k]} | {ci(m)} | {pct(m['recall'])} | {pct(m['precision'])} | {m['review_pct']:.2f}% | {m['fp_per_1000']:.2f} | {m['precision_at_k']['100']:.2f} |")
    return "\n".join(rows)

sC, sA, uC, uA = shf["C"], shf["A"], std["C"], std["A"]
ip, hp = lat["inproc"]["all"], lat["http_50rps"]
block = f"""<!-- results:start (generated by scripts/readme_results.py from eval/) -->
## TL;DR

- **Conservative headline (order-shuffled run): PR-AUC {sC['pr_auc']:.3f} vs {sA['pr_auc']:.3f}** for a transaction-only model ({sC['pr_auc'] / sA['pr_auc']:.0f}×), recall {pct(sC['recall'])} vs {pct(sA['recall'])}, about 1 in {round(1 / sC['precision'])} flags is laundering. Standard run (upper bound): PR-AUC {uC['pr_auc']:.3f}, recall {pct(uC['recall'])}.
- **Why two numbers:** timestamps are per minute, so the order inside a minute is only file order. The shuffled run randomises that order before building features, so the model cannot benefit from it.
- **About {ip['p50']:.1f} ms per decision on IBM z17** (in-process p50 {ip['p50']:.2f} ms, p99 {ip['p99']:.2f} ms over {ip['n']:,} payments; HTTP at {hp['target_rate']:.0f} req/s for {hp['seconds']:.0f} s: {hp['sent']:,} requests, {sum(hp['errors'].values())} errors, server-side p99 {hp['server_latency_ms']['p99']:.2f} ms).

## Results

IBM AML HI-Small (synthetic), first 2,000,000 payments by time, split 60/20/20 by time. Test: {rep['rows']['test']:,} payments, {rep['positives']['test']} laundering. Thresholds from validation only.

**Conservative: order shuffled within each minute** ([`eval/report_shuf.md`](eval/report_shuf.md))

{table(shf)}

**Standard run, upper bound** ([`eval/report.md`](eval/report.md))

{table(std)}

- Network signals carry the lift: in both runs, network-only beats transaction-only on PR-AUC ({shf['N']['pr_auc']:.3f} vs {sA['pr_auc']:.3f} conservative) and the combination beats both. In the conservative run, network-only recall ({pct(shf['N']['recall'])}) is below transaction-only ({pct(sA['recall'])}).
- About 1 in {round(1 / sC['precision'])} FLAGs is laundering (conservative run); the rest are false alarms, so a person decides.
<!-- results:end -->"""

readme = open("README.md").read()
if "<!-- results:start" in readme:
    readme = re.sub(r"<!-- results:start.*?<!-- results:end -->", lambda _: block, readme, flags=re.S)
else:
    start, end = readme.index("## TL;DR"), readme.index("### Limitations")
    mid = readme[start:end]
    keep = mid[mid.index("## The problem"):mid.index("## Results")]           # problem/approach/architecture stay between
    readme = readme[:start] + keep + block + "\n\n" + readme[end:]
open("README.md", "w").write(readme)
print("README results block regenerated")
